--기본적인 테이블 만드는 구조형식
CREATE TABLE EMP_DDL(
EMPNO NUMBER(4),
ENAME VARCHAR2(10),
JOB VARCHAR2(9),
MGR NUMBER(4),
HIREDATE DATE,
SAL NUMBER(7,2),
COMM NUMBER(7,2),
DEPTNO NUMBER(2)
);

DESC EMP;
DESC EMP_DDL;

--테이블을 만드는 구간인데 NOT널이 들어가는지 안들어가는지 테스트해본거다
CREATE TABLE DEPT_DDL
AS SELECT * FROM DEPT;

DESC DEPT_DDL;
SELECT *FROM DEPT_DDL;

--WHERE 조건을 사용하여 테이블을 만들수도 있다.
CREATE TABLE EMP_DDL_30
AS SELECT * FROM EMP
    WHERE DEPTNO = 30;

SELECT * FROM EMP_DDL_30;

--조건식이 항상 FASE 인 WHERE절은 테이블 공간만 가져오고싶을때 사용한다
-- WHERE 1<>1 을 사용하지 않을경우 데이터를 그대로 긁어오는대 그럴때
--데이터를 지우기위해서 딜리트를 사용하여야 한다
CREATE TABLE EMPDEPT_DDL
AS SELECT E.EMPNO, E.ENAME, E.JOB, E.MGR, E.HIREDATE, E.SAL, E.COMM,
            D.DEPTNO, D.DNAME, D.LOC
FROM EMP E, DEPT D
WHERE 1<>1;

SELECT * FROM EMPDEPT_DDL;
DESC EMPDEPT_DDL;

-- ADD 원하는 데이터 열을 추가하는데 쓰인다 열 속성값도 지정해줄수있다.
CREATE TABLE EMP_ALTER
AS SELECT * FROM EMP;
SELECT * FROM EMP_ALTER;

ALTER TABLE EMP_ALTER
ADD HP VARCHAR2(20);

SELECT * FROM EMP_ALTER;

--RENAME 원하는 열의 이름을 변경할수있다. ALTER문에 속하는 RENAME이기 때문에
--꼭 ALTER을 써줘야한다.
ALTER TABLE EMP_ALTER
RENAME COLUMN HP TO TEL;

SELECT * FROM EMP_ALTER;

--이미 있는데이터의 자료형을 바꾸려면 불가능하다
-- 비어있는 열자료형을 변경해야 가능하다
ALTER TABLE EMP_ALTER
MODIFY HP VARCHAR2(5);

DESC EMP_ALTER;

--ALTER 안에서의 DROP는 지우고싶은 열을 지울수있다.
ALTER TABLE EMP_ALTER
DROP COLUMN TEL;

SELECT * FROM EMP_ALTER;

-- WHERE 절을 사용하지 않은 DELETE문
TRUNCATE TABLE EMP_RENAME;

--DROP 테이블과 데이터 전부를 삭제하는 친구
DROP TABLE EMP_RENAME;
