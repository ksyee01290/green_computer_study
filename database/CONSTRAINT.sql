--제약조건
--NOT NULL = 지정한 열에 NULL 불가능 NULL외 데이터 중복 허용
--UNIQUE = 이메일같은거 지정한 열이 유일값을 가져야함 중복안됨 NULL값은 중복에서 제외
--PRIMARY KEY = 주민번호 같은거 지정한열이 유일한 값이여야함 NULL불가능 테이블당 하나만 지정가능
--FOREIGN KEY = 다른테이블의 열을 참조하여 존재하는 값만 입력할수있음 포린키가 없으면 조인을 할수가없음
--CHECK = (남/여)같은거 설정한 조건식을 만족하는 데이터만 입력가능

--NOT NULL
CREATE TABLE TABLE_NOTNULL(
LOGIN_ID VARCHAR2(20) NOT NULL,
LOGIN_PWD VARCHAR2(20) NOT NULL,
TEL VARCHAR2(20)
);
DESC TABLE_NOTNULL;

-- 아래와 같이 제약조건이 NOTNULL일경우 NULL값을 입력하면 오류가난다.
INSERT INTO TABLE_NOTNULL(LOGIN_ID, LOGIN_PWD, TEL)
VALUES('TEST_ID_01', NULL, '010-1234-5678');
INSERT INTO TABLE_NOTNULL(LOGIN_ID, LOGIN_PWD)
VALUES('TEST_ID_01','1234');

SELECT * FROM TABLE_NOTNULL;

--제약조건 확인 SELECT 에서 보고싶은 열이름을 입력하여 제약조건을 확인할수있다.
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS;

--아래의 CONSTRAINT는 옆에 이름으로 바꿔서 표시해준다는의미 이다
--따로 작성하지 않으면 컴퓨터에서 자동으로 지정해준다.
CREATE TABLE TABLE_NOTNULL2(
LOGIN_ID VARCHAR2(20) CONSTRAINT TBLNN2_LGNID_NN NOT NULL,
LOGIN_PWD VARCHAR2(20) CONSTRAINT TBLNN2_LGNPW_NN NOT NULL,
TEL VARCHAR2(20)
);
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS;

-- 아래는 이미 생성한 테이블에 제약조건을 지정하거나 수정할때 쓰이는 
--ALTER 의 MODIFY 를사용해야한다 하지만 지금 조건을보면 NOT NULL 이라고
--지정을 했는대 이미 테이블에 NULL 값이 들어 있다면 조건을 바꿀수없다.
ALTER TABLE TABLE_NOTNULL
MODIFY(TEL NOT NULL);

--아래의 업데이트 를 사용해서 원하는 열에 원하는값을 입력한다.
UPDATE TABLE_NOTNULL
SET TEL = '010-1234-5678'
WHERE LOGIN_ID = 'TEST_ID_01';

SELECT * FROM TABLE_NOTNULL;

--위에서와 같이 NULL값이 들어있던 TEL 열에 데이터를 집어넣었을 경우
--아래의 MODIFY를 사용해서 제약조건을 변경할수가 있다.
--프라이머리키는 테이블당 하나밖에 쓸수없으니 조심하자
ALTER TABLE TABLE_NOTNULL
MODIFY(TEL NOT NULL);

--아래와 같이 OWNER을 사용해서 컴퓨터 안에 있는 모든 제약조건을 검색해볼수있다.
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS;

ALTER TABLE TABLE_NOTNULL2
MODIFY(TEL NOT NULL);

--아래는 ALTER을 사용하여 이름을 새롭게 수정하는 부분이다 TO 앞에있는 제약조건명을
--꼭 알고있어야 변경이 가능하다. 처음에 만들때 이름을 지정안해줘서 한참 찾았다.
-- SYS_C008324 이게 시스템에서 지정해준 이름이다 이걸 아래와 같이 변경한다.
ALTER TABLE TABLE_NOTNULL2
RENAME CONSTRAINT SYS_C008324 TO TBLNN2_TEL_NN;

--아래와 같이 조건을 넣어 검색했을때 보면 ID,PWD는 둘다 CHECK 로
--지정되어 있다. NOT NULL은 CHECK로 표시가 되나보다
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME = 'TABLE_NOTNULL2';

--제약조건 삭제
ALTER TABLE TABLE_NOTNULL2
DROP CONSTRAINT TBLNN2_TEL_NN;

DESC TABLE_NOTNULL2;

--==========================UNIQUE=======================
--아래와 같이 새로 만드는 테이블에 제약조건을 걸어서 만든다
-- NOT NULL은 CHECK로 제약조건이 걸린다.
CREATE TABLE TABLE_UNIQUE(
LOGIN_ID VARCHAR2(20) UNIQUE,
LOGIN_PWD VARCHAR2(20) NOT NULL,
TEL VARCHAR2(20)
);

DESC TABLE_UNIQUE;

--이런식으로 제약조건에 테이블 이름을 넣어서 어떠한 제약조건이 있는지
-- 특정하여 검색할수도 있다.
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME = 'TABLE_UNIQUE';

--아래와 같이 유니크 속성인 ID에 똑같은걸 추가했더니 처음에 넣을때는 들어가지만
--무결성 제약조건에 의해 중복된 값은 제제 대상이 된다.
INSERT INTO TABLE_UNIQUE(LOGIN_ID, LOGIN_PWD, TEL)
VALUES('TEST_ID_01','PWD01','010-1234-5678');

SELECT * FROM TABLE_UNIQUE;

INSERT INTO TABLE_UNIQUE(LOGIN_ID, LOGIN_PWD, TEL)
VALUES('TEST_ID_01','PWD01','010-1234-5678');

--아래는 새롭게 UNIQUE2 테이블을 만든거다
CREATE TABLE TABLE_UNIQUE2(
LOGIN_ID VARCHAR2(20) CONSTRAINT TBLUNQ2_LGNID_UNQ UNIQUE,
LOGIN_PWD VARCHAR2(20) CONSTRAINT TBLUNQ2_LGNPW_NN NOT NULL,
TEL VARCHAR2(20)
);

--아래와 같이 LIKE를 사용하면 TABLE_UNIQUE에서 %를 사용했는데
--이것은 테이블에 포함된 모든걸 검색하겠다는 내용이다.
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME LIKE 'TABLE_UNIQUE%';

--이미 생성한 TEL 테이블에 제약조건을 지정한다.
ALTER TABLE TABLE_UNIQUE
MODIFY(TEL UNIQUE);

--업데이트 셋은 기존에 있던 데이터 자료를 원하는 SET 을설정해서 바꿀수있다.
UPDATE TABLE_UNIQUE
SET TEL = NULL;

SELECT * FROM TABLE_UNIQUE;

-- 아래와 같이 모디파이로 TEL의 제약조건을 유니크로 바꾸려했지만
--이미 텔 속성에 NULL 값이 있으므로 제약 조건변경은 불가능하다.
ALTER TABLE TABLE_UNIQUE
MODIFY(TEL UNIQUE);

--아래와 같이 이미 생성한 제약조건의 이름을 변경할수있다.
ALTER TABLE TABLE_UNIQUE2
RENAME CONSTRAINT TBLUNQ_TEL_UNQ TO TBLUNQ2_TEL_UNQ;

SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME LIKE 'TABLE_UNIQUE%';

--제약조건 삭제
ALTER TABLE TABLE_UNIQUE2
DROP CONSTRAINT TBLUNQ2_TEL_UNQ;

SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME LIKE 'TABLE_UNIQUE%';

--=======================PRIMARY KEY======================
--프라이머리키는 중복되는 데이터는 저장이 불가능하다. NULL도 저장이 불가능
--프라이머리키는 기본적으로 유니크와 낫널을 가진다 튜플검색이 가능하다.

--아래와같이 테이블을 생성한다.
CREATE TABLE TABLE_PK(
LOGIN_ID VARCHAR2(20) PRIMARY KEY,
LOGIN_PWD VARCHAR2(20) NOT NULL,
TEL VARCHAR2(20)
);
DESC TABLE_PK;

SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME LIKE 'TABLE_PK%';

--아래와 같이 이름을 지정해서 테이블을 생성한다.
CREATE TABLE TABLE_PK2(
LOGIN_ID VARCHAR2(20) CONSTRAINT TBLPK2_LGNID_PK PRIMARY KEY,
LOGIN_PWD VARCHAR2(20) CONSTRAINT TBLPK2_LGNPW_NN NOT NULL,
TEL VARCHAR2(20)
);
DESC TABLE_PK2;

--아래와 같이 대입을하면 처음 인서트만 데이터 삽입이 되고 나머지는 프라이머리
--키의 제약조건으로 데이터가 삽입되지 않는다.
INSERT INTO TABLE_PK(LOGIN_ID, LOGIN_PWD, TEL)
VALUES('TEST_ID_01', 'PWD01', '010-1234-5678');
INSERT INTO TABLE_PK(LOGIN_ID, LOGIN_PWD, TEL)
VALUES('TEST_ID_01', 'PWD02', '010-2345-6789');
INSERT INTO TABLE_PK(LOGIN_ID, LOGIN_PWD, TEL)
VALUES(NULL, 'PWD02', '010-2345-6789');
INSERT INTO TABLE_PK(LOGIN_PWD, TEL)
VALUES('PWD02', '010-2345-6789');

--아래와 같이 원하는 정보를 찾아서 볼수있다.
SELECT OWNER, CONSTRAINT_NAME, CONSTRAINT_TYPE, TABLE_NAME, R_OWNER, R_CONSTRAINT_NAME
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('EMP', 'DEPT');

--=======================FOREIGN KEY========================
--다른 테이블의 PRIMARY KEY 를 참조한다 참조하고 있는 키의 데이터 와 NULL 만 저장 가능
--우선 부모가 되는 테이블을 만들어줘야 한다.
CREATE TABLE DEPT_FK(
DEPTNO NUMBER(2) CONSTRAINT DEPTFK_DEPTNO_PK PRIMARY KEY,
DNAME VARCHAR2(14),
LOC VARCHAR2(13)
);

DESC DEPT_FK;

--자식 테이블도 만들어준다.
CREATE TABLE EMP_FK(
EMPNO NUMBER(4) CONSTRAINT EMPFK_EMPNO_PR PRIMARY KEY,
ENAME VARCHAR2(10),
JOB VARCHAR2(9),
MGR NUMBER(4),
HIREDATE DATE,
SAL NUMBER(7,2),
COMM NUMBER(7,2),
DEPTNO NUMBER(2) CONSTRAINT EMPFK_DEPTNO_FK REFERENCES DEPT_FK(DEPTNO)
);

--현재 지금 부모에 값이 없기때문에 무결성 제약조건으로 인서트가 되지 않는다.
INSERT INTO EMP_FK
VALUES(9999, 'TEST_NMAME', 'TEST_JOB', NULL,
    TO_DATE('2001/01/01', 'YYYY/MM/DD'),
    3000, NULL, 10);
    
